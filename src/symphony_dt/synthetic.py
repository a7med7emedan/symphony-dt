"""Synthetic PPMI-shaped input tables for demos, tests and containers.

PPMI data cannot be redistributed, so nothing derived from it ships with this package.
These tables have the same columns and value ranges the loader expects, with plausible
Parkinson's trajectories, so the full pipeline can run anywhere. Every value is invented.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

BASELINE_FILE = "baseline_table_PDLiKE.csv"
CLINIC_FILE = "clinic_visit_table_PDLiKE.csv"

# Score supports used by the observation model.
UPDRS3_MAX = 132.0
MOCA_MAX = 30.0
SCOPA_MAX = 69.0


def make_synthetic_tables(
    n_patients: int = 120, seed: int = 20240205, years: float = 5.0
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return (baseline, clinic) tables with the columns `load_ppmi_inputs` requires."""
    if n_patients < 1:
        raise ValueError("n_patients must be at least 1")
    rng = np.random.default_rng(seed)

    patient_ids = np.arange(100001, 100001 + n_patients)
    sex = rng.choice(["M", "F"], size=n_patients, p=[0.62, 0.38])
    age = np.round(rng.normal(62.0, 9.0, size=n_patients).clip(35, 85), 1)
    baseline = pd.DataFrame(
        {"patient_id": patient_ids, "sex": sex, "age_baseline_years": age, "is_pd_like": True}
    )

    rows = []
    for pid, s, a in zip(patient_ids, sex, age, strict=True):
        # Patient-specific progression: motor worsens, cognition and autonomic drift slowly.
        u0 = rng.normal(20, 8)
        u_rate = rng.lognormal(np.log(2.5), 0.4)  # UPDRS-III points per year
        m0 = rng.normal(27.5, 1.5)
        m_rate = -abs(rng.normal(0.25, 0.25)) - (0.2 if a > 70 else 0.0)
        s0 = rng.normal(9, 4)
        s_rate = abs(rng.normal(0.8, 0.4))
        on_meds_from = rng.uniform(0.3, 2.5)

        n_visits = int(rng.integers(5, 12))
        gaps = rng.uniform(120, 260, size=n_visits - 1)
        t_days = np.concatenate([[0.0], np.cumsum(gaps)])
        t_days = t_days[t_days <= years * 365.25]

        for k, t in enumerate(t_days):
            yrs = t / 365.25
            updrs = np.clip(u0 + u_rate * yrs + rng.normal(0, 3), 0, UPDRS3_MAX)
            moca = np.clip(m0 + m_rate * yrs + rng.normal(0, 1), 0, MOCA_MAX)
            scopa = np.clip(s0 + s_rate * yrs + rng.normal(0, 2), 0, SCOPA_MAX)
            ledd = 0.0 if yrs < on_meds_from else round(float(rng.normal(450, 150)) + 60 * yrs, 0)
            miss_u, miss_m, miss_s = (rng.random(3) < [0.05, 0.12, 0.10]).tolist()
            rows.append(
                {
                    "patient_id": pid,
                    "visit_id": "BL" if k == 0 else f"V{k:02d}",
                    "t_days_since_baseline": round(float(t), 1),
                    "updrs3_total": np.nan if miss_u else round(float(updrs), 0),
                    "moca_total": np.nan if miss_m else round(float(moca), 0),
                    "scopa_aut_total": np.nan if miss_s else round(float(scopa), 0),
                    "ledd_total": max(ledd, 0.0),
                    "miss_updrs3": miss_u,
                    "miss_moca": miss_m,
                    "miss_scopa": miss_s,
                    "sex": s,
                    "age_baseline_years": a,
                    "is_pd_like": True,
                }
            )
    clinic = pd.DataFrame(rows)
    return baseline, clinic


def write_synthetic_inputs(out_dir: Path, n_patients: int = 120, seed: int = 20240205) -> list[Path]:
    """Write the synthetic tables under the file names the default config expects."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    baseline, clinic = make_synthetic_tables(n_patients=n_patients, seed=seed)
    paths = [out_dir / BASELINE_FILE, out_dir / CLINIC_FILE]
    baseline.to_csv(paths[0], index=False)
    clinic.to_csv(paths[1], index=False)
    (out_dir / "README.txt").write_text(
        "Synthetic, PPMI-shaped tables generated by symphony-dt. No real participant data.\n"
    )
    return paths
