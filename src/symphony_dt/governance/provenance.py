"""Provenance in the shape of W3C PROV-JSON: entities, activities, agents and their relations.

Entities are identified by digests, never by content. A document can be written beside every
result, so a reader can follow which data fingerprint and which model produced which output.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from symphony_dt._version import __version__
from symphony_dt.labels import validation

__all__ = ["ProvenanceDocument"]


def _now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


@validation("TESTED")
@dataclass
class ProvenanceDocument:
    """A PROV-JSON document with the `sdt` namespace for symphony-dt identifiers.

    Validation: TESTED.
    """

    entities: dict[str, dict[str, Any]] = field(default_factory=dict)
    activities: dict[str, dict[str, Any]] = field(default_factory=dict)
    agents: dict[str, dict[str, Any]] = field(default_factory=dict)
    used: dict[str, dict[str, str]] = field(default_factory=dict)
    generated: dict[str, dict[str, str]] = field(default_factory=dict)
    associated: dict[str, dict[str, str]] = field(default_factory=dict)

    def entity(self, name: str, *, sha256: str, kind: str = "file", **attributes: Any) -> str:
        """Add an entity identified by its digest and return its PROV id.

        Validation: TESTED.
        """
        ident = f"sdt:{name}"
        self.entities[ident] = {"prov:type": kind, "sdt:sha256": sha256, **attributes}
        return ident

    def activity(self, name: str, *, started: str | None = None, ended: str | None = None, **attributes: Any) -> str:
        """Add an activity and return its PROV id.

        Validation: TESTED.
        """
        ident = f"sdt:{name}"
        self.activities[ident] = {
            "prov:startTime": started or _now(),
            "prov:endTime": ended or _now(),
            **attributes,
        }
        return ident

    def agent(self, name: str, *, kind: str = "prov:SoftwareAgent", **attributes: Any) -> str:
        """Add an agent and return its PROV id.

        Validation: TESTED.
        """
        ident = f"sdt:{name}"
        self.agents[ident] = {"prov:type": kind, **attributes}
        return ident

    def use(self, activity: str, entity: str) -> None:
        """Record that `activity` used `entity`.

        Validation: TESTED.
        """
        self.used[f"_:u{len(self.used) + 1}"] = {"prov:activity": activity, "prov:entity": entity}

    def generate(self, entity: str, activity: str) -> None:
        """Record that `entity` was generated by `activity`.

        Validation: TESTED.
        """
        self.generated[f"_:g{len(self.generated) + 1}"] = {"prov:entity": entity, "prov:activity": activity}

    def associate(self, activity: str, agent: str) -> None:
        """Record that `activity` was associated with `agent`.

        Validation: TESTED.
        """
        self.associated[f"_:a{len(self.associated) + 1}"] = {"prov:activity": activity, "prov:agent": agent}

    @classmethod
    def for_run(cls, activity: str, inputs: dict[str, str], outputs: dict[str, str]) -> ProvenanceDocument:
        """Build a document for one run: inputs and outputs given as name to sha256.

        Validation: TESTED.
        """
        doc = cls()
        software = doc.agent(f"symphony-dt-{__version__}", **{"sdt:version": __version__})
        act = doc.activity(activity)
        doc.associate(act, software)
        for name, digest in inputs.items():
            doc.use(act, doc.entity(name, sha256=digest))
        for name, digest in outputs.items():
            doc.generate(doc.entity(name, sha256=digest), act)
        return doc

    def to_dict(self) -> dict[str, Any]:
        """Return the PROV-JSON structure.

        Validation: TESTED.
        """
        return {
            "prefix": {
                "sdt": "https://a7med7emedan.github.io/symphony-dt/prov#",
                "prov": "http://www.w3.org/ns/prov#",
            },
            "entity": self.entities,
            "activity": self.activities,
            "agent": self.agents,
            "used": self.used,
            "wasGeneratedBy": self.generated,
            "wasAssociatedWith": self.associated,
        }

    def write(self, path: str | Path) -> Path:
        """Write the document as JSON and return the path.

        Validation: TESTED.
        """
        target = Path(path)
        target.write_text(json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n")
        return target
